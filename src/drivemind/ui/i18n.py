def language_label(code: str) -> str:
    for item_code, label in LANGUAGES:
        if item_code == code:
            return label
    return LANGUAGES[0][1]


def tr(code: str | None, key: str) -> str:
    lang = code or "ja"
    return TEXTS.get(lang, TEXTS["ja"]).get(key, TEXTS["ja"].get(key, key))
